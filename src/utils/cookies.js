const fs = require('fs');
const path = require('path');

/**
 * Converts a JSON cookie array to the Netscape HTTP Cookie File format.
 * @param {Array} cookiesArray 
 * @returns {string}
 */
function jsonToNetscape(cookiesArray) {
  let output = '# Netscape HTTP Cookie File\n';
  output += '# This file was automatically generated by the bot from cookies.json or YT_COOKIES env var.\n';
  output += '# Do not edit this file directly.\n\n';

  for (const cookie of cookiesArray) {
    if (!cookie.domain || !cookie.name) continue;

    const domain = cookie.domain;
    const flag = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const pathVal = cookie.path || '/';
    const secure = cookie.secure ? 'TRUE' : 'FALSE';
    const expiry = cookie.expirationDate ? Math.round(cookie.expirationDate) : 0;
    const name = cookie.name;
    const value = cookie.value || '';

    output += `${domain}\t${flag}\t${pathVal}\t${secure}\t${expiry}\t${name}\t${value}\n`;
  }
  return output;
}

/**
 * Loads YouTube cookies, generates cookies.txt, and configures yt-dlp.
 * @returns {Array|undefined} Parsed cookie array if found, otherwise undefined.
 */
function setupCookies() {
  let cookies = null;

  // 1. Try to load from environment variable YT_COOKIES
  if (process.env.YT_COOKIES) {
    let rawCookies = process.env.YT_COOKIES.trim();
    try {
      // Robust cleanup: if wrapped in outer quotes, strip them
      if (rawCookies.startsWith('"') && rawCookies.endsWith('"')) {
        rawCookies = rawCookies.substring(1, rawCookies.length - 1);
      } else if (rawCookies.startsWith("'") && rawCookies.endsWith("'")) {
        rawCookies = rawCookies.substring(1, rawCookies.length - 1);
      }
      
      // Unescape escaped double quotes (\") and newlines (\n) if present
      rawCookies = rawCookies.replace(/\\"/g, '"')
                             .replace(/\\n/g, '\n')
                             .replace(/\\\\/g, '\\');

      cookies = JSON.parse(rawCookies);
      console.log('✅ [Cookies Helper] Loaded cookies from YT_COOKIES environment variable');
    } catch (err) {
      console.error('⚠️ [Cookies Helper] Failed to parse YT_COOKIES environment variable:', err.message);
    }
  }

  // 2. Try to load from local cookies.json file
  if (!cookies) {
    const cookiesJsonPath = path.join(process.cwd(), 'cookies.json');
    if (fs.existsSync(cookiesJsonPath)) {
      try {
        const content = fs.readFileSync(cookiesJsonPath, 'utf8');
        cookies = JSON.parse(content);
        console.log('✅ [Cookies Helper] Loaded cookies from cookies.json');
      } catch (err) {
        console.error('⚠️ [Cookies Helper] Failed to read or parse cookies.json:', err.message);
      }
    }
  }

  // Find the yt-dlp package bin directory
  const ytDlpBinDir = path.join(process.cwd(), 'bin');
  const confPath = path.join(ytDlpBinDir, 'yt-dlp.conf');


  if (cookies && Array.isArray(cookies) && cookies.length > 0) {
    try {
      // Write Netscape cookies.txt to project root
      const cookiesTxtPath = path.join(process.cwd(), 'cookies.txt');
      const netscapeContent = jsonToNetscape(cookies);
      fs.writeFileSync(cookiesTxtPath, netscapeContent, 'utf8');
      console.log('✅ [Cookies Helper] Generated cookies.txt in Netscape format');

      // Configure yt-dlp portable configuration in its binary directory
      if (fs.existsSync(ytDlpBinDir)) {
        const normalizedCookiesPath = cookiesTxtPath.replace(/\\/g, '/');
        const confContent = `# Generated by cookies.js\n--cookies "${normalizedCookiesPath}"\n`;
        fs.writeFileSync(confPath, confContent, 'utf8');
        console.log(`✅ [Cookies Helper] Configured yt-dlp config at: ${confPath}`);
      } else {
        console.warn(`⚠️ [Cookies Helper] yt-dlp bin directory not found at: ${ytDlpBinDir}. yt-dlp will run without config file.`);
      }

      return cookies;
    } catch (err) {
      console.error('⚠️ [Cookies Helper] Failed to write cookies or configuration file:', err.message);
    }
  } else {
    console.log('ℹ️ [Cookies Helper] No cookies configured. Running in unauthenticated mode.');
    // Cleanup old config files if they exist to prevent using stale cookies
    if (fs.existsSync(confPath)) {
      try {
        fs.unlinkSync(confPath);
        console.log('🧹 [Cookies Helper] Cleaned up stale yt-dlp.conf');
      } catch (err) {
        // ignore error
      }
    }
    const cookiesTxtPath = path.join(process.cwd(), 'cookies.txt');
    if (fs.existsSync(cookiesTxtPath)) {
      try {
        fs.unlinkSync(cookiesTxtPath);
        console.log('🧹 [Cookies Helper] Cleaned up stale cookies.txt');
      } catch (err) {}
    }
  }

  return undefined;
}

module.exports = { setupCookies };
